// Precision / recall / F1 for Alert 2 (potentially related cases) on the labelled test set.
// Run from apps/web: npx tsx src/scripts/eval-overlap.mjs
// Writes the results to docs/overlap-eval.md at the repo root.

import fs from "node:fs";
import { pipeline } from "@huggingface/transformers";
import { scorePair, RELATED_THRESHOLD } from "../lib/overlap/scoring.ts";

const MODEL = "Xenova/paraphrase-multilingual-mpnet-base-v2";
const DAY_MS = 86_400_000;
const testset = JSON.parse(fs.readFileSync(new URL("./overlap-testset.json", import.meta.url), "utf8"));

const extractor = await pipeline("feature-extraction", MODEL);
const cache = new Map();
async function embed(text) {
  if (!cache.has(text)) {
    const out = await extractor(text, { pooling: "mean", normalize: true });
    cache.set(text, Array.from(out.data));
  }
  return cache.get(text);
}

function levenshtein(a, b) {
  let prev = Array.from({ length: b.length + 1 }, (_, j) => j);
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    for (let j = 1; j <= b.length; j++) {
      cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
    }
    prev = cur;
  }
  return prev[b.length];
}

// Stand-in for the pg_trgm institution match: normalised names within a small edit distance.
const normName = s => s.toLowerCase().replace(/[^a-z0-9]/g, "");
function sameInstitution(x, y) {
  const a = normName(x), b = normName(y);
  return a === b || levenshtein(a, b) <= Math.max(2, Math.floor(a.length * 0.1));
}

function withinDays(d1, d2, days) {
  return !!d1 && !!d2 && Math.abs(new Date(d1) - new Date(d2)) <= days * DAY_MS;
}

const rows = [];
for (const it of testset) {
  const a = { text: it.a.text, category: it.a.category, bureau: it.a.bureau, date: it.a.date, embedding: await embed(it.a.text) };
  const b = { text: it.b.text, category: it.b.category, bureau: it.b.bureau, date: it.b.date, embedding: await embed(it.b.text) };
  const sameInst = sameInstitution(it.a.institution, it.b.institution);
  rows.push({
    id: it.id,
    category: it.category,
    truth: it.expect_alert2,
    sameInst,
    score: scorePair(a, b).score,
    baseline: sameInst && it.a.category === it.b.category && withinDays(it.a.date, it.b.date, 30),
  });
}

function metrics(predict) {
  let tp = 0, fp = 0, fn = 0;
  for (const r of rows) {
    const p = predict(r);
    if (p && r.truth) tp++;
    else if (p) fp++;
    else if (r.truth) fn++;
  }
  const precision = tp + fp ? tp / (tp + fp) : 0;
  const recall = tp + fn ? tp / (tp + fn) : 0;
  const f1 = precision + recall ? (2 * precision * recall) / (precision + recall) : 0;
  return { tp, fp, fn, precision, recall, f1 };
}

const pct = x => (x * 100).toFixed(1);
const thresholds = [0.4, 0.45, 0.5, 0.55, 0.6, 0.65, 0.7, 0.75, 0.8];
const scoreRows = thresholds.map(t => {
  const m = metrics(r => r.sameInst && r.score >= t);
  return `| ${t.toFixed(2)} | ${pct(m.precision)} | ${pct(m.recall)} | ${pct(m.f1)} | ${m.tp} | ${m.fp} | ${m.fn} |`;
});
const base = metrics(r => r.baseline);

const categories = [...new Set(rows.map(r => r.category))];
const catRows = categories.map(c => {
  const subset = rows.filter(r => r.category === c);
  const hits = subset.filter(r => r.sameInst && r.score >= RELATED_THRESHOLD);
  const expected = subset.filter(r => r.truth).length;
  const correct = hits.filter(r => r.truth).length;
  return `| ${c} | ${subset.length} | ${expected} | ${hits.length} | ${correct} |`;
});

const doc = `# Overlap detection: Alert 2 evaluation

Generated by \`apps/web/src/scripts/eval-overlap.mjs\` on ${new Date().toISOString().slice(0, 10)}.

- Test set: \`apps/web/src/scripts/overlap-testset.json\`, ${rows.length} labelled pairs (synthetic, Appendix B mix).
- Model: \`${MODEL}\` (768-dim, mean pooling, normalised).
- Ground truth: \`expect_alert2\`. A pair counts as predicted when both cases share an institution (fuzzy name match) and the score reaches the threshold.
- Configured threshold: ${RELATED_THRESHOLD}. Cosine gate: cosine below 0.5 caps the score under the threshold.

## Weighted score vs threshold

| Threshold | Precision % | Recall % | F1 % | TP | FP | FN |
|---|---|---|---|---|---|---|
${scoreRows.join("\n")}

## Rules-only baseline (same institution + same category + filed within 30 days)

| Method | Precision % | Recall % | F1 % | TP | FP | FN |
|---|---|---|---|---|---|---|
| Rules only | ${pct(base.precision)} | ${pct(base.recall)} | ${pct(base.f1)} | ${base.tp} | ${base.fp} | ${base.fn} |

## Per category at threshold ${RELATED_THRESHOLD}

| Pair category | Pairs | Expected alerts | Alerts raised | Correct alerts |
|---|---|---|---|---|
${catRows.join("\n")}

## Notes

- Alert 1 (cross-bureau) is a SQL rule and is not scored here. \`expect_alert1\` in the test set is kept for that check.
- The test set is synthetic and template-generated, so these numbers are a sanity check, not evidence of real-world accuracy.
- Incomplete records (missing date or bureau) show how the score degrades when a factor is absent.
`;

fs.writeFileSync(new URL("../../../../docs/overlap-eval.md", import.meta.url), doc, "utf8");

console.log(`Pairs: ${rows.length}`);
console.log("threshold  precision  recall     f1   tp  fp  fn");
for (const t of thresholds) {
  const m = metrics(r => r.sameInst && r.score >= t);
  console.log(`${t.toFixed(2)}       ${pct(m.precision).padStart(6)}  ${pct(m.recall).padStart(6)}  ${pct(m.f1).padStart(6)}  ${m.tp} ${m.fp} ${m.fn}`);
}
console.log(`baseline   ${pct(base.precision).padStart(6)}  ${pct(base.recall).padStart(6)}  ${pct(base.f1).padStart(6)}  ${base.tp} ${base.fp} ${base.fn}`);
console.log("Wrote docs/overlap-eval.md");
